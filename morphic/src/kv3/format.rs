//! KV3 schema identifiers. Binary payloads store a GUID, not a schema name.

use crate::error::DecodeError;

/// The 16-byte KV3 format GUID from the payload header. It names the schema
/// (soundevents, material, generic, ...); the engine keys on it, so a faithful
/// re-encode must carry the original through rather than substitute a generic.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Format(pub [u8; 16]);

impl Format {
    /// Read the schema GUID from legacy VKV3 or a binary KV3 v1..=5 payload.
    /// Errors if the slice is too short or not supported binary KV3.
    pub fn from_payload(data: &[u8]) -> Result<Self, DecodeError> {
        let legacy = data.get(..4) == Some(&[0x56, 0x4b, 0x56, 0x03]);
        if !legacy {
            super::reader::version(data)?;
        }
        if data.len() < 20 {
            return Err(DecodeError::Truncated {
                offset: 0,
                needed: 20,
                had: data.len(),
            });
        }
        let mut guid = [0u8; 16];
        let start = if legacy { 20 } else { 4 };
        guid.copy_from_slice(
            data.get(start..start + 16)
                .ok_or(DecodeError::Kv3("Truncated format GUID"))?,
        );
        Ok(Self(guid))
    }

    /// Schema name resolved from VRF's GUID table, or `None` for unknown GUIDs.
    #[must_use]
    pub fn name(&self) -> Option<&'static str> {
        NAMES
            .iter()
            .find_map(|(guid, name)| (guid == &self.0).then_some(*name))
    }

    /// Canonical lowercase GUID, with the first three fields in GUID byte order.
    #[must_use]
    pub fn guid(&self) -> String {
        let b = self.0;
        format!(
            "{:08x}-{:04x}-{:04x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
            u32::from_le_bytes(b[0..4].try_into().unwrap()),
            u16::from_le_bytes(b[4..6].try_into().unwrap()),
            u16::from_le_bytes(b[6..8].try_into().unwrap()),
            b[8],
            b[9],
            b[10],
            b[11],
            b[12],
            b[13],
            b[14],
            b[15]
        )
    }
}

